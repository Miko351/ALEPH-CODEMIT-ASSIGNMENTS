-- Preserve the Day1 events table and its rows when upgrading this project.
DO $$
BEGIN
    IF to_regclass('public.http_events') IS NULL AND to_regclass('public.events') IS NOT NULL THEN
        ALTER TABLE public.events RENAME TO http_events;
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    name text NOT NULL,
    password_hash text NOT NULL
);
CREATE TABLE IF NOT EXISTS http_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL,
    method text NOT NULL,
    path text NOT NULL,
    status_code integer NOT NULL CHECK (status_code BETWEEN 100 AND 599),
    duration_ms double precision NOT NULL CHECK (duration_ms >= 0)
);
CREATE TABLE IF NOT EXISTS notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL CHECK (length(trim(title)) > 0),
    body text NOT NULL CHECK (length(trim(body)) > 0),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Upgrade existing notes without deleting or rewriting their title/body.
-- Existing notes receive the initial status; repeated initialization is safe.
ALTER TABLE notes ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_progress', 'completed'));

ALTER TABLE http_events ADD COLUMN IF NOT EXISTS event_kind text NOT NULL DEFAULT 'request' CHECK (event_kind IN ('request', 'login_failure', 'login_success'));
